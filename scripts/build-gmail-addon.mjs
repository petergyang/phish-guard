import { mkdir, copyFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { build } from "esbuild";

const repoRoot = process.cwd();
const outDir = path.join(repoRoot, "dist", "gmail-addon");
const codePath = path.join(outDir, "Code.js");

await mkdir(outDir, { recursive: true });

await build({
  entryPoints: [path.join(repoRoot, "apps", "gmail-addon", "src", "apps-script-entry.ts")],
  bundle: true,
  outfile: codePath,
  platform: "browser",
  format: "iife",
  target: "es2020",
  globalName: "GmailPhishGuard",
  footer: {
    js: "function onGmailMessage(e) { return GmailPhishGuard.onGmailMessage(e); }"
  },
  logLevel: "silent"
});

await copyFile(
  path.join(repoRoot, "apps", "gmail-addon", "appsscript.json"),
  path.join(outDir, "appsscript.json")
);

await writeFile(
  path.join(outDir, "README.md"),
  [
    "# Gmail Phish Guard Apps Script Build",
    "",
    "This directory is generated by `npm run build:gmail-addon`.",
    "Push it to Apps Script with `npm run deploy:gmail-addon` after creating or linking a clasp project.",
    ""
  ].join("\n")
);

console.log(`Built Gmail add-on Apps Script files in ${path.relative(repoRoot, outDir)}`);
